"""Build widths.js: advance widths of printable characters in Arial at the sizes Google uses
for desktop result titles (20px) and descriptions (14px). Run on a Mac: python3 tools/make_widths.py"""
import json
from PIL import ImageFont

FONT = "/System/Library/Fonts/Supplemental/Arial.ttf"
RANGES = [(0x20, 0x7F), (0xA0, 0x180), (0x370, 0x3D0), (0x400, 0x460)]   # Latin, Latin-1, Latin Extended-A, Greek, Cyrillic
CHARS = "".join(chr(c) for a, b in RANGES for c in range(a, b)) + "–—‘’“”…•·€₹™"
FONT_CMAP = None


def covered():
    from fontTools.ttLib import TTFont   # only characters Arial really contains
    return set(TTFont(FONT).getBestCmap())


def table(size, keep):
    f = ImageFont.truetype(FONT, size * 10)   # measure at 10x, then scale, for sub-pixel accuracy
    return {ch: round(f.getlength(ch) / 10, 2) for ch in CHARS if ord(ch) in keep and ch.isprintable()}


keep = covered()
t, d = table(20, keep), table(14, keep)
out = ("// Generated by tools/make_widths.py from Arial: character widths in pixels.\n"
       "(function (root) {\n"
       f"  var W = {{ title: {json.dumps(t, ensure_ascii=False)},\n"
       f"    desc: {json.dumps(d, ensure_ascii=False)} }};\n"
       f"  W.titleDefault = {round(sum(t[c] for c in 'abcdefghijklmnopqrstuvwxyz') / 26, 2)};\n"
       f"  W.descDefault = {round(sum(d[c] for c in 'abcdefghijklmnopqrstuvwxyz') / 26, 2)};\n"
       "  if (typeof module === 'object' && module.exports) module.exports = W; else root.SNIPPET_WIDTHS = W;\n"
       "})(this);\n")
open("widths.js", "w", encoding="utf-8").write(out)
print("ok", t["a"], t["W"], d["a"], d["W"])
